#!/usr/bin/env python3
"""Sensitivity analyses of the analytic readout -> LaTeX macros.

Reads extension_stage/sensitivity_readout.json and writes
outputs/generated/sensitivity_macros.tex, so that no figure of these analyses is
typed by hand in the manuscript or the supplement.

    python3 tools/build_sensitivity_macros.py
"""
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import repo_data  # noqa: E402

ROOT = repo_data.ROOT
SRC = repo_data.stage(2) / "sensitivity_readout.json"
OUT = ROOT / "outputs" / "generated" / "sensitivity_macros.tex"

# analysis key in the JSON -> macro stem
ANALYSES = {
    "dfa_speaker_balanced": "Weight",     # rows replicated: isolates the weighting
    "dfa_speaker_weighted": "Averaged",   # one averaged row per speaker
    "dfa_no_mask": "Mask",                # Whisper frames pooled without the mask
}
METRICS = {"speaker_auroc": "Auroc", "speaker_macro_f1": "MacroF"}


def pp(v):
    return f"{v:+.2f}"


def prob(v):
    return "--" if v is None else f"{v:.3f}"


def main():
    raw = SRC.read_bytes()
    data = json.loads(raw)
    lines = [
        "%% GENERATED by tools/build_sensitivity_macros.py -- DO NOT EDIT BY HAND.",
        f"%% Source: extension_stage/{SRC.name} sha256[:16]={hashlib.sha256(raw).hexdigest()[:16]}",
    ]

    def emit(name, value):
        lines.append(f"\\newcommand{{\\sen{name}}}{{{value}}}")

    for key, stem in ANALYSES.items():
        for metric, mstem in METRICS.items():
            r = data["analyses"][key][metric]["all"]
            emit(f"{stem}{mstem}Blocks", r["blocks"])
            emit(f"{stem}{mstem}Fav", r["favourable"])
            emit(f"{stem}{mstem}Med", pp(r["median"]))
            emit(f"{stem}{mstem}Min", pp(r["min"]))
            emit(f"{stem}{mstem}Max", pp(r["max"]))
            emit(f"{stem}{mstem}P", prob(r.get("p")))
            emit(f"{stem}{mstem}Q", prob(r.get("q")))
    emit("FamilyM", data["family"]["n_tests"])
    emit("Cells", data["cells"])
    dose = data["mask_dose_response"]
    emit("MaskDoseRho", f"{dose['spearman_rho']:+.2f}")
    emit("MaskDoseP", prob(dose["p"]))
    emit("MaskDoseN", dose["n"])
    lo, hi = data["whisper_real_frame_fraction_range"]
    emit("RealFrameMinPct", f"{100 * lo:.1f}")
    emit("RealFrameMaxPct", f"{100 * hi:.1f}")
    lo, hi = data["windows_per_speaker_range"]
    emit("WindowsPerSpkMin", f"{lo:.1f}")
    emit("WindowsPerSpkMax", f"{hi:.1f}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines) - 2} macros)")


if __name__ == "__main__":
    main()
