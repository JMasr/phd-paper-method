#!/usr/bin/env python3
"""End-to-end cost of a cell, search included -> LaTeX macros.

Reads extension_stage/cell_wall_clock.csv and the hpo_trials.csv of both stages (extracted once from
the campaign logs) and writes outputs/generated/cost_macros.tex, so that no figure of the search cost is
typed by hand.

What the macros carry (prefix \\tel):
  \\telDfaWallS, \\telLoraWallS, \\telDoraWallS, \\telRadialWallS, \\telDfaLastWallS
        median wall-clock seconds of one corpus x backbone x partition cell at rank 8 in the extension
        stage, from launch to exit of the cell's process: feature extraction, the learning-rate search,
        the training of the selected configuration and the test evaluation (the packaged \\...TrainS
        macros cover the selected training run only).
  \\telWallGradMin / \\telWallGradMax      the smallest and largest of the three gradient-arm medians
  \\telWallRatioMin / \\telWallRatioMax    gradient median / readout median
  \\telDfaWallSavingMin / \\telDfaWallSavingMax   percentage less time for the readout
  \\telCellsPerArm                          cells per arm behind each median
  \\telTrialsGradTwo, \\telTrialsDfaTwo, \\telTrialsOne   learning-rate trials per fold file: gradient arms
        and the readout in the extension stage, every arm in the screening stage
  \\telDfaSearchCellsOne, \\telDfaSearchFilesOne, \\telDfaSearchRangeMaxOne, \\telDfaSearchNonzeroOne
        the screening-stage search of the readout: cells, trial files, the largest within-file range of
        the validation score, and the number of files where it was not zero

Every expectation is checked and a violation stops the build:

    python3 tools/build_cost_macros.py
"""
from __future__ import annotations
import csv, hashlib, json, statistics, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import repo_data  # noqa: E402

OUT = repo_data.ROOT / "outputs" / "generated" / "cost_macros.tex"
PRIMARY = {"dfa": "Dfa", "lora": "Lora", "dora": "Dora", "radial_lora_v3": "Radial", "dfa_last": "DfaLast"}
GRADIENT = ("lora", "dora", "radial_lora_v3")
CLOSED_FORM = ("dfa", "dfa_last", "dfa_sph")


def die(m: str):
    sys.stderr.write("ERROR: " + m + "\n"); sys.exit(1)


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    global OUT
    if "--out" in sys.argv:                                # --out <folder> writes the macros elsewhere
        OUT = Path(sys.argv[sys.argv.index("--out") + 1]).expanduser().resolve() / OUT.name
    wall = repo_data.rows(2, "cell_wall_clock.csv")
    hpo = repo_data.both_stages("hpo_trials.csv")
    if len(wall) != repo_data.manifest(2)["bundle"]["runs"]: die("cell_wall_clock.csv does not hold one row per run of the extension stage")

    # ---- per-cell wall clock, extension stage, rank 8, cells that produced a result --------------
    med = {}
    cells = set()
    for arm in PRIMARY:
        sel = [r for r in wall if r["adapter"] == arm and r["rank"] == "8"]
        bad = [r for r in sel if r["status"] != "OK"]
        if bad: die(f"{arm}: {len(bad)} rank-8 cells with status != OK ({sorted({r['status'] for r in bad})})")
        if not sel: die(f"{arm}: no rank-8 cells in the extract")
        med[arm] = statistics.median(float(r["wall_s"]) for r in sel); cells.add(len(sel))
    if len(cells) != 1: die(f"arms carry different cell counts: {sorted(cells)}")
    n_cells = cells.pop()
    expected_cells = len({(r["corpus"], r["model"]) for r in wall}) * 3   # three partitions per block
    if n_cells != expected_cells: die(f"{n_cells} cells per arm, expected {expected_cells}")

    # ---- learning-rate trials ----------------------------------------------------------------------
    def row(stage: str, arm: str, rank: str = "8") -> dict:
        m = [r for r in hpo if (r["stage"], r["adapter"], r["rank"]) == (stage, arm, rank)]
        if len(m) != 1: die(f"hpo_trials_summary.csv: {len(m)} rows for stage {stage} {arm} r{rank}")
        return m[0]
    trials_one = {row("1", a)["trials_per_file"] for a in list(PRIMARY) if a != "dfa_sph"}
    if len(trials_one) != 1: die(f"screening stage: trials per file differ across arms: {sorted(trials_one)}")
    trials_grad = {row("2", a)["trials_per_file"] for a in GRADIENT}
    trials_cf = {row("2", a)["trials_per_file"] for a in CLOSED_FORM}
    if len(trials_grad) != 1 or len(trials_cf) != 1: die("extension stage: trials per file differ within the gradient or the closed-form arms")
    d1 = row("1", "dfa")
    if float(d1["val_score_range_max"]) != 0.0 or int(d1["files_with_nonzero_range"]) != 0:
        die("the readout's validation score varied across learning-rate trials in the screening stage; the text asserts it did not")

    lines = ["%% GENERATED by tools/build_cost_macros.py -- DO NOT EDIT BY HAND.",
             "%% Source: extension_stage/cell_wall_clock.csv and {screening,extension}_stage/hpo_trials.csv"]

    def emit(n, v): lines.append(f"\\newcommand{{\\tel{n}}}{{{v}}}")
    for arm, stem in PRIMARY.items(): emit(f"{stem}WallS", f"{med[arm]:.0f}")
    g = {a: med[a] for a in GRADIENT}
    emit("WallGradMin", f"{min(g.values()):.0f}"); emit("WallGradMax", f"{max(g.values()):.0f}")
    emit("WallRatioMin", f"{min(g.values()) / med['dfa']:.1f}"); emit("WallRatioMax", f"{max(g.values()) / med['dfa']:.1f}")
    emit("DfaWallSavingMin", f"{100 * (1 - med['dfa'] / min(g.values())):.0f}"); emit("DfaWallSavingMax", f"{100 * (1 - med['dfa'] / max(g.values())):.0f}")
    emit("CellsPerArm", str(n_cells))
    emit("TrialsGradTwo", trials_grad.pop()); emit("TrialsDfaTwo", trials_cf.pop()); emit("TrialsOne", trials_one.pop())
    emit("DfaSearchCellsOne", d1["cells"]); emit("DfaSearchFilesOne", d1["trial_files"])
    emit("DfaSearchRangeMaxOne", f"{float(d1['val_score_range_max']):.4f}"); emit("DfaSearchNonzeroOne", d1["files_with_nonzero_range"])
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines) - 2} macros); cell wall clock at rank 8: " +
          ", ".join(f"{a} {med[a]:.0f} s" for a in PRIMARY))


if __name__ == "__main__":
    main()
